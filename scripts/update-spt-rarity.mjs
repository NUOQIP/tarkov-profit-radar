import {readFile,writeFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';

// Pin updates explicitly; visitors never download the full SPT database.
const commit=process.argv[2]||'9b490cfb1585e8a24e1a86941ec59a0a85b5dd1f';
if(!/^[0-9a-f]{40}$/.test(commit))throw new Error('Pass a full tarkynator commit SHA');
const source=`https://raw.githubusercontent.com/emilanderss0n/tarkynator/${commit}/data/items.json`;
const response=process.argv[3]?null:await fetch(source);
if(response&&!response.ok)throw new Error(`SPT source: HTTP ${response.status}`);
const bytes=process.argv[3]?await readFile(process.argv[3]):Buffer.from(await response.arrayBuffer());
const items=Object.values(JSON.parse(bytes)),groups={Common:[],Rare:[],Superrare:[]},counts={};
for(const item of items){
  const rarity=item._props?.RarityPvE||'missing';counts[rarity]=(counts[rarity]||0)+1;
  if(Object.hasOwn(groups,rarity)){
    if(!/^[0-9a-f]{24}$/.test(item._id))throw new Error('Invalid SPT item ID');
    groups[rarity].push(item._id);
  }
}
if(items.length<4000||Object.values(groups).some(g=>g.length<100))throw new Error('Incomplete SPT rarity data');
for(const group of Object.values(groups))group.sort();
const metadata={source,commit,field:'_props.RarityPvE',version:'SPT 4.1+',items:items.length,counts,sha256:createHash('sha256').update(bytes).digest('hex')};
const output=`// Generated by scripts/update-spt-rarity.mjs; Not_exist and absent fields remain unknown.\nexport const SPT_SOURCE=${JSON.stringify(metadata)};\nexport const SPT_GROUPS=${JSON.stringify(groups)};\n`;
await writeFile(new URL('../app/spt-rarity.mjs',import.meta.url),output);
console.log(JSON.stringify({items:items.length,classified:Object.values(groups).reduce((n,g)=>n+g.length,0),bytes:Buffer.byteLength(output),counts}));
